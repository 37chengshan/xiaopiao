export type ReceiptKey = Parameters<typeof s>[0];

/** Subscribe to locale changes and hand back the dictionary for this render. */
export function useReceiptStrings(): (key: ReceiptKey) => string {
  useLocale();
  return s;
}

/** Fills `{}` placeholders in order. The dictionary keeps the sentence, this keeps the values. */
export function fill(template: string, ...values: string[]): string {
  let i = 0;
  return template.replace(/\{\}/g, () => values[i++] ?? "");
}
