    private fun o(id: String, label: String, profile: String? = null, emoji: String = "") =
        GameOption(id = id, label = label, profile = profile, emoji = emoji)

    private fun choice(id: String, prompt: String, vararg options: GameOption) =
        ChoiceQuestion(id = id, prompt = prompt, options = options.toList())

    private fun typeQ(id: String, prompt: String, left: String, leftKey: String, right: String, rightKey: String) =
        ChoiceQuestion(
            id = id,
            prompt = prompt,
            options = listOf(
                GameOption(id = "${id}a", label = left, profile = leftKey),
                GameOption(id = "${id}b", label = right, profile = rightKey),
            ),
        )

    /**
     * The last three strings are the result-page keyword chips; the five before them are the analysis.
     * Keeping this convention means the 16 profiles stay readable instead of becoming a wall of named lists.
     */
    private fun profile(
        key: String,
        emoji: String,
        label: String,
        blurb: String,
        vararg content: String,
    ): GameProfile {
        val split = content.size > 5
        return GameProfile(
            key = key,
            emoji = emoji,
            label = label,
            blurb = blurb,
            insights = if (split) content.dropLast(3).toList() else content.toList(),
            keywords = if (split) content.takeLast(3).toList() else emptyList(),
        )
    }

    private fun typeProfile(
        key: String,
        emoji: String,
        label: String,
        blurb: String,
        vararg content: String,
    ) = profile(key, emoji, label, blurb, *content)

    /** `quiz(id, prompt, a, b, c, correct, explain)` — exactly three options, one of them correct. */
    private fun quiz(
        id: String,
        prompt: String,
        a: String,
        b: String,
        c: String,
        correct: String,
        explain: String,
    ): QuizQuestion {
        val options = listOf(
            GameOption("$id-a", a),
            GameOption("$id-b", b),
            GameOption("$id-c", c),
        )
        val correctId = options.firstOrNull { it.label == correct }?.id ?: options.first().id
        return QuizQuestion(id = id, prompt = prompt, options = options, correctId = correctId, explain = explain)
    }
